CREATE TABLE IF NOT EXISTS auto_reply_rules (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    unique_id CHAR(30) NOT NULL,
    project_id VARCHAR(191) NOT NULL,
    name VARCHAR(120) NOT NULL,
    rule_type VARCHAR(16) NOT NULL,
    keywords TEXT NOT NULL,
    match_type VARCHAR(16) NOT NULL DEFAULT 'contains',
    reply_payload TEXT NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
    days_of_week VARCHAR(20) NOT NULL DEFAULT '',
    business_hours TINYINT(1) NOT NULL DEFAULT 0,
    start_time TIME NULL,
    end_time TIME NULL,
    priority INT UNSIGNED NOT NULL DEFAULT 1,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    triggered_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
    last_triggered_at DATETIME NULL,
    create_date DATETIME NOT NULL,
    create_by VARCHAR(191) NOT NULL,
    modify_date DATETIME NOT NULL,
    modify_by VARCHAR(191) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uniq_auto_reply_rule_id (unique_id),
    KEY idx_auto_reply_project_active_priority (project_id, is_active, priority, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
